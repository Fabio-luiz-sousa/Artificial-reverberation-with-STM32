void processHalf(void)
{
	controlSettingsReady = 0;
    for (uint16_t n = 0; n < BUFFER_SIZE / 2; n++)
    {
        float audioIn;
        float audioOut;

        audioIn = ((float)inBufPtr[n] - 2048.0f) / 2048.0f;

        float comb_sum = CombFilterUpdate(&comb, audioIn, 0, &comb.comDelay[0])+ CombFilterUpdate(&comb, audioIn, 1, &comb.comDelay[1])+
        		CombFilterUpdate(&comb, audioIn, 2, &comb.comDelay[2]) + CombFilterUpdate(&comb, audioIn, 3, &comb.comDelay[3]);
        comb_sum *= 0.25f;
        float allpass1 = AllPassFilterUpdate(&allp, comb_sum, &allp.allpDelay[0], 0);
        float allpass2 = AllPassFilterUpdate(&allp, allpass1, &allp.allpDelay[1], 1);

        audioOut = audioIn*(1-wet) + allpass2*(wet);
        //audioOut  = audioIn;

        if (audioOut > 1.0f)
            audioOut = 1.0f;

        if (audioOut < -1.0f)
            audioOut = -1.0f;

        //audioOut *= outputVolume;
        outBufPtr[n] =
            (uint16_t)((audioOut + 1.0f) * 2047.5f);

    }
    controlSettingsReady = 1;
}


void HAL_ADC_ConvHalfCpltCallback(ADC_HandleTypeDef *hadc){
	if (hadc->Instance == ADC1){
		inBufPtr = &adcx[0];
		outBufPtr = &dacx[0];
		processHalf();
	}


}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc){
	if (hadc->Instance == ADC1){
		inBufPtr = &adcx[BUFFER_SIZE/2];
		outBufPtr = &dacx[BUFFER_SIZE/2];
		processHalf();
	}
	else if (hadc->Instance == ADC3){

		controlSettingsReady = 0;
		for (uint8_t n=0; n <3 ;n++){
			float pot = adcControlPot[n]/4095.0f;

			controlSettings[n] =
			    controlSettings[n]
			    + 0.2696f * (pot - controlSettings[n]);

		}
		controlSettingsReady = 1;

	}


}


